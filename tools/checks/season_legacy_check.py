#!/usr/bin/env python3
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def read(p): return (ROOT/p).read_text(encoding="utf-8")
def need(src,text,label):
    if text not in src: raise AssertionError(f"{label}: missing {text!r}")
cfg=read("src/ReplicatedStorage/Config/SeasonConfig.luau")
plan=read("src/ReplicatedStorage/Shared/SeasonPlan.luau")
service=read("src/ServerScriptService/Services/SeasonService.luau")
player=read("src/ServerScriptService/Services/PlayerService.luau")
bees=read("src/ReplicatedStorage/Config/BeesConfig.luau")
need(cfg,'Hive=8',"Season Hive threshold")
need(cfg,'Flowers=8',"Season Flower threshold")
need(cfg,'Bees=5',"Season Bee threshold")
need(cfg,'Quests=15',"Season Quest threshold")
assert "Trials" not in cfg and "TrialIds" not in cfg
need(service,'self.X.QuestService:ClaimedCount(p)>=C.Quests',"Quest eligibility")
need(service,'p.Hive.Level>=C.Hive',"Hive eligibility")
need(service,'string.format("Season: Hive %d, %d quests, %d flowers, %d bees",C.Hive,C.Quests,C.Flowers,C.Bees)',"requirement copy")
assert "BuildTrialService" not in service and "Quests.Trials" not in service
need(service,'local token=Http:GenerateGUID(false)',"preview token")
need(service,'Revision=self.X.Revisions[player]',"preview revision")
need(service,'if q.Revision~=self.X.Revisions[player] or not self.X.U.Equal(q.Before,p) then',"stale preview")
need(service,'local result=self.X.DataService:CommitProfile(player,plan.After,token)',"transactional commit")
need(player,'SEASON_PREVIEW_OPEN',"preview mutation lock")
need(plan,'UnlockedSlots=1',"reset Garden slot")
need(plan,'after.Currencies.Coins=0',"Coin reset")
need(plan,'after.Currencies.AncientNectar=after.Currencies.AncientNectar+C.SeasonReward+E.Value(profile,"LEGACY_6","SeasonNectar",0)',"Nectar reward")
need(plan,'TotalHoney=profile.Hive.TotalHoney',"lifetime Honey")
need(plan,'after.Season.Count=profile.Season.Count+1',"Season count")
need(plan,'if not after.WorkshopV5.LegacyNodes[id] then',"Legacy retention")
need(plan,'local bee=profile.Season.Keepsakes.Bee or "WorkerBee"',"Bee keepsake")
need(service,'self.X.GardenActivityService:CancelGarden(player)',"activity cleanup")
need(service,'self.X.PollinatorService:Remove(player)',"pollinator cleanup")
need(service,'self.X.GardenPlotService:Build(player)',"garden rebuild")
need(bees,"function C.GetMasteryState(totalXP:number?):any","Bee Mastery")
print("season / legacy contract: PASS")
print("Season uses 15 claimed Quests instead of Trials; transaction, reset and Legacy retention remain server-authoritative.")
